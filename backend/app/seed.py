"""Зачекированная тестовая выборка задач для US-1 / FR-1.

Детерминированные демо-данные: реалистичная структура с зависимостями,
чтобы Гант сразу выглядел осмысленно при открытии.
"""
from __future__ import annotations

from .core.plan import Task
from .core.scheduler import forward_pass, find_critical_path

# Список кортежей: (задача, описание, исполнитель, длительность, предшественники)
RAW_TASKS = [
    ("Инициация", "Сбор требований и согласование целей проекта", "Анна", 3, []),
    ("Анализ", "Анализ требований и подготовка ТЗ", "Борис", 4, ["Инициация"]),
    ("Дизайн", "Прототип интерфейса и UX-макет", "Вика", 5, ["Анализ"]),
    ("Разработка бэкенда", "Реализация API и бизнес-логики", "Борис", 8, ["Анализ"]),
    ("Разработка фронтенда", "Реализация клиентской части", "Гриша", 6, ["Дизайн"]),
    ("Интеграция", "Стыковка бэкенда и фронтенда", "Дарья", 4, ["Разработка бэкенда", "Разработка фронтенда"]),
    ("Тестирование", "Функциональное и приёмочное тестирование", "Елена", 5, ["Интеграция"]),
    ("Документация", "Подготовка документации и инструкций", "Анна", 2, ["Тестирование"]),
    ("Релиз", "Деплой и передача в эксплуатацию", "Дарья", 2, ["Документация"]),
]


def build_seed_tasks() -> list[Task]:
    tasks = []
    for name, desc, assignee, dur, preds in RAW_TASKS:
        tasks.append(
            Task(name=name, description=desc, assignee=assignee, duration_days=dur, predecessors=list(preds))
        )
    forward_pass({t.name: t for t in tasks})
    find_critical_path({t.name: t for t in tasks})
    return tasks


SEED_TASKS: list[Task] = build_seed_tasks()