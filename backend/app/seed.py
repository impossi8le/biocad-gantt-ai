"""Зачекированная тестовая выборка задач для US-1 / FR-1.

Детерминированные демо-данные: реалистичная структура с зависимостями,
чтобы Гант сразу выглядел осмысленно при открытии.
"""
from __future__ import annotations

from .core.plan import Task
from .core.scheduler import forward_pass, find_critical_path

# Список кортежей: (задача, описание, исполнитель, длительность, предшественники)
# Включает длинные задачи (>30 дней) для демонстрации месяцев/лет и бейджа «>1 мес».
RAW_TASKS = [
    ("Инициация", "Сбор требований и согласование целей проекта", "Анна", 3, []),
    ("Анализ", "Анализ требований и подготовка ТЗ", "Борис", 4, ["Инициация"]),
    ("Прототипирование", "Прототип интерфейса и UX-макет", "Вика", 5, ["Анализ"]),
    ("Разработка бэкенда", "Реализация API и бизнес-логики", "Борис", 12, ["Анализ"]),
    ("Разработка фронтенда", "Реализация клиентской части", "Гриша", 10, ["Прототипирование"]),
    ("Дизайн-система", "Компоненты и дизайн-токены (полтора месяца)", "Вика", 45, ["Прототипирование"]),
    ("База данных", "Модель данных и миграции", "Борис", 8, ["Анализ"]),
    ("Интеграция", "Стыковка бэкенда и фронтенда", "Дарья", 5, ["Разработка бэкенда", "Разработка фронтенда"]),
    ("Нагрузочное тестирование", "Тесты производительности (2 месяца)", "Елена", 60, ["Интеграция"]),
    ("Функциональное тестирование", "Функциональное и приёмочное тестирование", "Елена", 6, ["Интеграция"]),
    ("Документация", "Подготовка документации и инструкций", "Анна", 4, ["Функциональное тестирование"]),
    ("Подготовка релиза", "Сборка и подготовка релизного кандидата", "Дарья", 3, ["Документация", "Нагрузочное тестирование"]),
    ("Релиз", "Деплой и передача в эксплуатацию", "Дарья", 2, ["Подготовка релиза"]),
]


def build_seed_tasks() -> list[Task]:
    tasks = []
    for name, desc, assignee, dur, preds in RAW_TASKS:
        tasks.append(
            Task(name=name, description=desc, assignee=assignee, duration_days=dur, predecessors=list(preds))
        )
    forward_pass({t.name: t for t in tasks})
    find_critical_path({t.name: t for t in tasks})
    return tasks


SEED_TASKS: list[Task] = build_seed_tasks()